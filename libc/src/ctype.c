static inline int ctype_check(int c, uint8_t mask)
{
    if (c < 0 || c > 127)
        return 0;

    return (lookup_table[c] & mask) != 0;
}

int isalnum(int c)
{
    return ctype_check(c, CTYPE_UPPER | CTYPE_LOWER | CTYPE_DIGIT);
}

int isalpha(int c)
{
    return ctype_check(c, CTYPE_UPPER | CTYPE_LOWER);
}

int iscntrl(int c)
{
    return ctype_check(c, CTYPE_CONTROL);
}

int isdigit(int c)
{
    return ctype_check(c, CTYPE_DIGIT);
}

int isgraph(int c)
{
    return ctype_check(c, CTYPE_UPPER | CTYPE_LOWER | CTYPE_DIGIT | CTYPE_PUNCT);
}

int islower(int c)
{
    return ctype_check(c, CTYPE_LOWER);
}

int isprint(int c)
{
    return isgraph(c) || c == ' ';
}

int ispunct(int c)
{
    return ctype_check(c, CTYPE_PUNCT);
}

int isspace(int c)
{
    return ctype_check(c, CTYPE_SPACE);
}

int isupper(int c)
{
    return ctype_check(c, CTYPE_UPPER);
}

int isxdigit(int c)
{
    return ctype_check(c, CTYPE_XDIGIT | CTYPE_DIGIT);
}

int isblank(int c)
{
    return ctype_check(c, CTYPE_BLANK);
}

